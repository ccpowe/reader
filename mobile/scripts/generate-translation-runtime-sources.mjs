import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSync } from 'esbuild';
import ts from 'typescript';

const mobileRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(mobileRoot, 'domain/translationRuntimeSources.generated.ts');
const youtubeSpecification = {
  constantName: 'YOUTUBE_TRANSLATION_BOOTSTRAP_SOURCE',
  functionName: 'youTubeTranslationBootstrap',
  sourcePath: resolve(mobileRoot, 'domain/youtubeTranslation.ts'),
};

function transpileFunction({ functionName, sourcePath }) {
  const sourceText = readFileSync(sourcePath, 'utf8');
  const sourceFile = ts.createSourceFile(
    sourcePath,
    sourceText,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const declaration = sourceFile.statements.find(
    (statement) =>
      ts.isFunctionDeclaration(statement) && statement.name?.text === functionName,
  );
  if (!declaration) throw new Error(`Could not find ${functionName} in ${sourcePath}`);

  const result = ts.transpileModule(declaration.getText(sourceFile), {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
    },
    fileName: sourcePath,
    reportDiagnostics: true,
  });
  const errors = (result.diagnostics ?? []).filter(
    (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error,
  );
  if (errors.length) {
    throw new Error(
      errors
        .map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'))
        .join('\n'),
    );
  }

  const transpiledSource = result.outputText.trim();
  const runtime = new Function(`${transpiledSource}\nreturn ${functionName};`)();
  if (typeof runtime !== 'function') throw new Error(`${functionName} did not transpile to a function`);
  const functionSource = runtime.toString();
  new Function(`(${functionSource})({channelToken:"validation",initialMode:"original"});`);
  return functionSource;
}

function bundleWebRuntime() {
  const result = buildSync({
    absWorkingDir: mobileRoot,
    entryPoints: [resolve(mobileRoot, 'domain/webTranslationRuntime.ts')],
    bundle: true,
    format: 'iife',
    globalName: 'ReaderWebTranslationRuntime',
    platform: 'browser',
    target: ['es2022'],
    write: false,
    legalComments: 'none',
    minify: false,
    preserveSymlinks: true,
  });
  const bundle = result.outputFiles[0]?.text.trim();
  if (!bundle) throw new Error('Web translation runtime bundle is empty');
  const functionSource = `function readerWebTranslationBootstrap(config){${bundle}\nReaderWebTranslationRuntime.webTranslationBootstrap(config);}`;
  new Function(`return (${functionSource});`)();
  return functionSource;
}

const webRuntime = bundleWebRuntime();
const runtimeVersion = createHash('sha256').update(webRuntime).update(readFileSync(resolve(mobileRoot, 'domain/webTranslationRules.ts'))).digest('hex').slice(0, 16);
const generated = [
  '// Generated by scripts/generate-translation-runtime-sources.mjs.',
  '// Do not edit directly; edit the typed runtime modules instead.',
  '',
  `export const WEB_TRANSLATION_RUNTIME_VERSION = ${JSON.stringify(runtimeVersion)};`,
  `export const WEB_TRANSLATION_BOOTSTRAP_SOURCE = ${JSON.stringify(webRuntime)};`,
  `export const ${youtubeSpecification.constantName} = ${JSON.stringify(transpileFunction(youtubeSpecification))};`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = readFileSync(outputPath, 'utf8');
  if (current !== generated) {
    console.error('Translation runtime sources are stale. Run pnpm run generate:translation-runtime.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, generated);
  console.log('generated domain/translationRuntimeSources.generated.ts');
}
